-- Refresh tokens con rotación: cada uso emite un token nuevo de la misma familia (una sesión de un
-- dispositivo) y deja el anterior marcado como rotado. Si un token rotado se presenta fuera de la
-- gracia de refresco concurrente, se revoca toda la familia.
ALTER TABLE refresh_tokens
    ADD COLUMN family_id VARCHAR(36),
    -- Tope de la familia desde el inicio de sesión; los sucesores lo heredan.
    ADD COLUMN absolute_expiry TIMESTAMP,
    ADD COLUMN rotated_at TIMESTAMP,
    -- Sucesores extra emitidos dentro de la gracia por refrescos concurrentes (dos pestañas).
    ADD COLUMN grace_successors INTEGER NOT NULL DEFAULT 0;

-- Tokens anteriores (de hasta 365 días): cada uno forma su propia familia y sigue valiendo hasta rotar
-- en su próximo uso. Su tope pasa a 60 días desde el inicio de sesión, pero nunca antes de 30 días desde
-- este despliegue, para no cerrar de golpe las sesiones que ya superaban los 60 días.
UPDATE refresh_tokens
SET family_id = gen_random_uuid()::text,
    absolute_expiry = LEAST(
        created_at + INTERVAL '365 days',
        GREATEST(created_at + INTERVAL '60 days', (now() AT TIME ZONE 'UTC') + INTERVAL '30 days'));
UPDATE refresh_tokens SET expiry_date = LEAST(expiry_date, absolute_expiry);

ALTER TABLE refresh_tokens
    ALTER COLUMN family_id SET NOT NULL,
    ALTER COLUMN absolute_expiry SET NOT NULL;
CREATE INDEX idx_refresh_tokens_family_id ON refresh_tokens (family_id);

-- Recuperar la contraseña por correo: token de un solo uso, guardado solo como hash SHA-256.
CREATE TABLE password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash VARCHAR(64) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    used_at TIMESTAMPTZ
);
CREATE INDEX idx_password_reset_tokens_user ON password_reset_tokens (user_id);
CREATE INDEX idx_password_reset_tokens_expires ON password_reset_tokens (expires_at);
