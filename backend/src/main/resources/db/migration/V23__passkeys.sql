-- Llaves de acceso (WebAuthn, PasskeyService): entrar con huella, cara o el PIN del dispositivo
-- sin contraseña. Solo se guarda la clave pública; la privada nunca sale del dispositivo.
CREATE TABLE passkeys (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id VARCHAR(36) NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    credential_id BYTEA NOT NULL UNIQUE,
    -- Identificador aleatorio de la cuenta para el autenticador, igual en todas sus llaves.
    user_handle BYTEA NOT NULL,
    public_key_cose BYTEA NOT NULL,
    signature_count BIGINT NOT NULL DEFAULT 0,
    name VARCHAR(60) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    last_used_at TIMESTAMPTZ
);
CREATE INDEX idx_passkeys_user ON passkeys (user_id);
CREATE INDEX idx_passkeys_user_handle ON passkeys (user_handle);

-- Reto de un registro o un inicio de sesión en curso. Un solo uso; caduca en 5 minutos.
CREATE TABLE passkey_challenges (
    id VARCHAR(64) PRIMARY KEY,
    -- Solo en los registros: la cuenta que añade la llave.
    user_id VARCHAR(36) REFERENCES users(id) ON DELETE CASCADE,
    request_json TEXT NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX idx_passkey_challenges_expires ON passkey_challenges (expires_at);
