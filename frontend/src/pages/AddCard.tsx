import { createImportJob, saveImportJob, type ImportJob } from '../services/noteImport';
import { useQueryClient } from '@tanstack/react-query';
import { invalidateStudyData } from '../lib/queryInvalidation';
import toast from 'react-hot-toast';
import { useState, useEffect, useRef, KeyboardEvent } from 'react';
import { useParams, useNavigate, Link } from 'react-router-dom';
import { notesApi, aiApi } from '../services/api';
import { handleImagePaste, compressImageFromPaste } from '../utils/imageUtils';
import { lookupDefinition } from '../utils/definitionService';
import ImageSearchModal from '../components/ImageSearchModal';
import { useDecks } from '../hooks/useDecks';
import { SegmentedControl } from '../components/ui/segmented-control';
import { BookA, Info, ListPlus, Image, Folder, Search, X } from 'lucide-react';
import { formatTermHeading, htmlToText } from '../lib/utils';
import { SelectMenu } from '../components/ui/select-menu';
import FlashCard from '../components/FlashCard';

const NOTE_TYPES = [
  { id: 'basic', name: 'Básica', description: 'Una tarjeta: ves el frente y respondes el dorso.' },
  {
    id: 'reverse',
    name: 'Básica + Reversa',
    description: 'Dos tarjetas: la normal y otra al revés, que enseña el dorso y pide el frente.',
  },
];

const isAutoGenerated = (html: string) => {
  if (typeof html !== 'string') return false;
  return html.includes('data-auto="true"');
};

export default function AddCard() {
  const queryClient = useQueryClient();
  const { deckId: paramDeckId } = useParams<{ deckId: string }>();
  const navigate = useNavigate();

  const {
    data: decks = [],
    isLoading: loadingDecks,
    isError: errorDecks,
    refetch: retryDecks,
  } = useDecks();
  const [selectedDeckId, setSelectedDeckId] = useState<string>(paramDeckId || '');
  const [selectedType, setSelectedType] = useState<string>('basic');
  const [addMode, setAddMode] = useState<'single' | 'mass'>('single');
  const [fields, setFields] = useState({ front: '', back: '' });
  const [tags, setTags] = useState<string[]>([]);
  const [tagInput, setTagInput] = useState<string>('');
  const [previewFlipped, setPreviewFlipped] = useState(false);
  const [typeInfoOpen, setTypeInfoOpen] = useState(false);
  const [previewReversed, setPreviewReversed] = useState(false);
  const [massInput, setMassInput] = useState<string>('');
  const [saving, setSaving] = useState<boolean>(false);
  const [massGenerating, setMassGenerating] = useState<boolean>(false);
  const pendingImport = useRef<ImportJob | null>(null);
  const importInFlight = useRef(false);
  const [importProgress, setImportProgress] = useState<{ saved: number; total: number } | null>(
    null,
  );

  const [lookingUpDef, setLookingUpDef] = useState<boolean>(false);

  /** `auto` crea una tarjeta de imagen: la foto elegida al frente y el término detrás. */
  const [imageSearchModalInfo, setImageSearchModalInfo] = useState<{
    field: 'front' | 'back' | 'auto';
    query: string;
  } | null>(null);

  const frontFileRef = useRef<HTMLInputElement>(null);
  const backFileRef = useRef<HTMLInputElement>(null);
  const tagInputRef = useRef<HTMLInputElement>(null);
  const frontContentRef = useRef<HTMLDivElement>(null);
  const backContentRef = useRef<HTMLDivElement>(null);

  useEffect(() => {
    if (decks.length > 0 && !decks.some((deck) => deck.id === selectedDeckId))
      setSelectedDeckId(decks[0].id);
  }, [decks, selectedDeckId]);

  const clearEditor = () => {
    setFields({ front: '', back: '' });
    if (frontContentRef.current) frontContentRef.current.innerHTML = '';
    if (backContentRef.current) backContentRef.current.innerHTML = '';
  };

  const insertHtmlAtCursor = (html: string, contentRef: React.RefObject<HTMLDivElement | null>) => {
    if (!contentRef.current) return;
    contentRef.current.focus();
    let selection = window.getSelection();
    if (!selection || selection.rangeCount === 0) return;
    let range = selection.getRangeAt(0);

    const isWithinRef = contentRef.current.contains(range.commonAncestorContainer);
    if (!isWithinRef) {
      range = document.createRange();
      range.selectNodeContents(contentRef.current);
      range.collapse(false);
      selection.removeAllRanges();
      selection.addRange(range);
    }

    range.deleteContents();
    const el = document.createElement('div');
    el.innerHTML = html;
    const frag = document.createDocumentFragment();
    let node, lastNode;
    while ((node = el.firstChild)) {
      lastNode = frag.appendChild(node);
    }
    range.insertNode(frag);
    if (lastNode) {
      range = range.cloneRange();
      range.setStartAfter(lastNode);
      range.collapse(true);
      selection.removeAllRanges();
      selection.addRange(range);
    }
  };

  const handleFieldChange = (field: 'front' | 'back') => (e: React.FormEvent<HTMLDivElement>) => {
    let content = e.currentTarget.innerHTML;
    if (content === '<br>') content = '';

    if (field === 'back' && isAutoGenerated(fields.front) && !content) {
      const movedHtml = formatTermHeading(fields.front);
      setFields((prev) => ({ ...prev, front: '', back: movedHtml }));
      if (frontContentRef.current) frontContentRef.current.innerHTML = '';
      if (backContentRef.current) backContentRef.current.innerHTML = movedHtml;
      setTimeout(() => {
        const sel = window.getSelection();
        if (!sel || !backContentRef.current) return;
        const range = document.createRange();
        range.selectNodeContents(backContentRef.current);
        range.collapse(false);
        sel.removeAllRanges();
        sel.addRange(range);
      }, 0);
      return;
    }

    setFields((prev) => ({ ...prev, [field]: content }));
  };

  const handlePaste =
    (field: 'front' | 'back') => async (e: React.ClipboardEvent<HTMLDivElement>) => {
      handleImagePaste(e, () => {
        setFields((prev) => ({
          ...prev,
          [field]:
            field === 'front' && frontContentRef.current
              ? frontContentRef.current.innerHTML
              : backContentRef.current
                ? backContentRef.current.innerHTML
                : '',
        }));
      });
    };

  const handleFileSelected = (field: 'front' | 'back', e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    compressImageFromPaste(file).then((base64: string) => {
      const imgHtml = `<img src="${base64}" />`;
      if (field === 'front') insertHtmlAtCursor(imgHtml, frontContentRef);
      else insertHtmlAtCursor(imgHtml, backContentRef);
      setFields((prev) => ({
        ...prev,
        [field]:
          field === 'front' && frontContentRef.current
            ? frontContentRef.current.innerHTML
            : backContentRef.current
              ? backContentRef.current.innerHTML
              : '',
      }));
      e.target.value = '';
    });
  };

  const handleGalleryPick = (field: 'front' | 'back') => {
    if (field === 'front') frontFileRef.current?.click();
    else backFileRef.current?.click();
  };

  const handleOpenImageSearch = (field: 'front' | 'back') => {
    const query =
      htmlToText(fields[field] || '').trim() ||
      (field === 'back' ? htmlToText(fields.front || '').trim() : '');
    setImageSearchModalInfo({ field, query });
  };

  const handleImageSearchSelect = (url: string, field: 'front' | 'back' | 'auto') => {
    const imgHtml = `<img src="${url.replace(/"/g, '%22')}" alt="" />`;
    setImageSearchModalInfo(null);
    if (field === 'auto') {
      const back = formatTermHeading(imageSearchModalInfo?.query ?? '');
      if (frontContentRef.current) frontContentRef.current.innerHTML = imgHtml;
      if (backContentRef.current) backContentRef.current.innerHTML = back;
      setFields((prev) => ({ ...prev, front: imgHtml, back }));
      return;
    }
    if (field === 'front') insertHtmlAtCursor(imgHtml, frontContentRef);
    else insertHtmlAtCursor(imgHtml, backContentRef);
    setFields((prev) => ({
      ...prev,
      [field]:
        field === 'front' && frontContentRef.current
          ? frontContentRef.current.innerHTML
          : backContentRef.current
            ? backContentRef.current.innerHTML
            : '',
    }));
  };

  const handleDefinition = async () => {
    const term = htmlToText(fields.front || '').trim();
    if (!term) return toast.error('Escribe un término en el frente primero');
    setLookingUpDef(true);
    try {
      const def = await lookupDefinition(term);
      if (!def?.definition) {
        toast.error(`No he encontrado una definición para «${term}»`);
        return;
      }
      // La definición es texto: se inserta como tal para no interpretar HTML ajeno.
      const front = frontContentRef.current;
      const backHtml = formatTermHeading(fields.front);
      if (front) front.textContent = def.definition;
      if (backContentRef.current) backContentRef.current.innerHTML = backHtml;
      setFields((prev) => ({
        ...prev,
        front: front?.innerHTML ?? def.definition,
        back: backHtml,
      }));
    } catch (e: unknown) {
      toast.error(e instanceof Error ? e.message : 'Error buscando definicion');
    } finally {
      setLookingUpDef(false);
    }
  };

  const handleAutoImage = () => {
    const term = htmlToText(fields.front || '').trim();
    if (!term) return toast.error('Escribe un término en el frente primero');
    setImageSearchModalInfo({ field: 'auto', query: term });
  };

  const handleAdd = async (closeAfter: boolean) => {
    if (!selectedDeckId) return toast.error('Selecciona un mazo');
    if (!fields.front.trim() || !fields.back.trim())
      return toast.error('El frente y el dorso son obligatorios');

    setSaving(true);
    try {
      const fieldsJson = JSON.stringify({ front: fields.front, back: fields.back });
      await notesApi.create({
        deckId: selectedDeckId,
        noteType: selectedType,
        fieldsJson,
        tags: tags.join(','),
      });
      await invalidateStudyData(queryClient, selectedDeckId);
      toast.success('Tarjeta añadida');
      clearEditor();
      if (closeAfter) navigate('/');
    } catch (e: unknown) {
      toast.error(e instanceof Error ? e.message : 'Error al guardar');
    } finally {
      setSaving(false);
    }
  };

  const handleMassAdd = async () => {
    if (
      importInFlight.current ||
      (!pendingImport.current && (!massInput.trim() || !selectedDeckId))
    )
      return;
    importInFlight.current = true;
    setMassGenerating(true);
    try {
      if (!pendingImport.current) {
        const lines = massInput
          .split(/[\n,]+/)
          .map((line) => line.trim())
          .filter(Boolean);
        const generated = await aiApi.massDefine(lines.join('\n'));
        pendingImport.current = createImportJob(selectedDeckId, generated, tags.join(','));
      }
      const job = pendingImport.current;
      await saveImportJob(job, (saved, total) => setImportProgress({ saved, total }));
      await invalidateStudyData(queryClient, job.deckId);
      toast.success(`Guardadas ${job.notes.length} tarjetas`);
      pendingImport.current = null;
      setImportProgress(null);
      setMassInput('');
    } catch (error: unknown) {
      if (pendingImport.current?.saved)
        await invalidateStudyData(queryClient, pendingImport.current.deckId);
      toast.error(error instanceof Error ? error.message : 'No se ha completado el guardado');
    } finally {
      importInFlight.current = false;
      setMassGenerating(false);
    }
  };

  const handleTagKeyDown = (e: KeyboardEvent<HTMLInputElement>) => {
    if (e.key === 'Enter' || e.key === ',') {
      e.preventDefault();
      const tag = tagInput
        .trim()
        .toLowerCase()
        .replace(/[^a-z0-9-]/g, '');
      if (tag && !tags.includes(tag)) setTags([...tags, tag]);
      setTagInput('');
    } else if (e.key === 'Backspace' && tagInput === '' && tags.length > 0) {
      setTags(tags.slice(0, -1));
    }
  };
  const removeTag = (t: string) => setTags(tags.filter((x) => x !== t));

  useEffect(() => {
    const handler = (e: globalThis.KeyboardEvent) => {
      if (e.key === 'Enter' && (e.ctrlKey || e.metaKey)) {
        e.preventDefault();
        if (addMode === 'single') handleAdd(false);
        else handleMassAdd();
      }
    };
    window.addEventListener('keydown', handler);
    return () => window.removeEventListener('keydown', handler);
  }, [fields, selectedDeckId, selectedType, tags, massInput, addMode]);

  if (errorDecks)
    return (
      <div className="card page-state" role="alert">
        <h2>No se han podido cargar tus mazos</h2>
        <button className="sheet-action" onClick={() => void retryDecks()}>
          Reintentar
        </button>
      </div>
    );
  if (loadingDecks)
    return (
      <div className="page-state" role="status">
        <div className="spinner" />
        <p>Cargando mazos…</p>
      </div>
    );
  if (decks.length === 0)
    return (
      <div className="card page-state">
        <h2>Todavía no tienes mazos</h2>
        <p>Crea un mazo antes de añadir tarjetas.</p>
        <Link className="sheet-action" to="/">
          Ir a Mis Mazos
        </Link>
      </div>
    );

  const emptySide = (text: string) => `<span style="color:var(--text-muted)">${text}</span>`;
  const reversed = selectedType === 'reverse' && previewReversed;
  const previewFront = (reversed ? fields.back : fields.front) || emptySide('Pregunta');
  const previewBack = (reversed ? fields.front : fields.back) || emptySide('Respuesta');

  // Dónde va la tarjeta y de qué tipo es: cabecera de la hoja, en los dos modos.
  const targetFields = (
    <div className="add-card-fields">
      <div className="add-card-field">
        <label htmlFor="add-card-deck" className="form-label">
          Mazo
        </label>
        <SelectMenu
          id="add-card-deck"
          value={selectedDeckId}
          onChange={setSelectedDeckId}
          options={decks.map((d) => ({ value: d.id, label: d.name }))}
          disabled={massGenerating || !!pendingImport.current}
          aria-label="Seleccionar mazo"
          menuLabel="Mazo"
        />
      </div>
      {addMode === 'single' && (
        <div className="add-card-field">
          <div className="add-card-label-row">
            <span className="form-label" id="add-card-note-type">
              Tipo de nota
            </span>
            {/* La explicación sale al pasar el ratón, al enfocar o al tocar; no ocupa sitio fijo. */}
            <span
              className="add-card-info"
              onMouseEnter={() => setTypeInfoOpen(true)}
              onMouseLeave={() => setTypeInfoOpen(false)}
            >
              <button
                type="button"
                className="add-card-info-btn"
                aria-label="Qué es cada tipo de nota"
                aria-expanded={typeInfoOpen}
                aria-describedby={typeInfoOpen ? 'add-card-type-info' : undefined}
                onClick={() => setTypeInfoOpen(true)}
                onFocus={() => setTypeInfoOpen(true)}
                onBlur={() => setTypeInfoOpen(false)}
                onKeyDown={(e) => e.key === 'Escape' && setTypeInfoOpen(false)}
              >
                <Info size={16} aria-hidden="true" />
              </button>
              {typeInfoOpen && (
                <span className="add-card-info-pop" role="tooltip" id="add-card-type-info">
                  {NOTE_TYPES.map((t) => (
                    <span key={t.id}>
                      <strong>{t.name}</strong>
                      {t.description}
                    </span>
                  ))}
                </span>
              )}
            </span>
          </div>
          <div role="group" aria-labelledby="add-card-note-type">
            <SegmentedControl
              options={NOTE_TYPES.map((t) => ({ label: t.name, value: t.id }))}
              value={selectedType}
              onChange={(value) => {
                if (value === selectedType) return;
                setSelectedType(value);
                clearEditor();
              }}
              className="add-card-types"
            />
          </div>
        </div>
      )}
    </div>
  );

  return (
    <div className="fade-in add-card-page">
      <SegmentedControl
        options={[
          { label: 'Una a una', value: 'single' },
          { label: 'En masa', value: 'mass' },
        ]}
        value={addMode}
        onChange={(val) => setAddMode(val as 'single' | 'mass')}
        className="mb-6 w-full"
      />

      <div hidden>
        <input
          ref={frontFileRef}
          type="file"
          accept="image/*"
          style={{ display: 'none' }}
          onChange={(e) => handleFileSelected('front', e)}
        />
        <input
          ref={backFileRef}
          type="file"
          accept="image/*"
          style={{ display: 'none' }}
          onChange={(e) => handleFileSelected('back', e)}
        />
      </div>

      {addMode === 'mass' ? (
        <div className="card" style={{ marginBottom: '1.5rem' }}>
          {targetFields}
          <p
            style={{
              margin: '0 0 16px 0',
              fontSize: '0.9rem',
              color: 'var(--text-muted)',
              textAlign: 'center',
            }}
          >
            Escribe o pega una lista de conceptos (separados por comas o saltos de línea) para
            autogenerar las tarjetas.
          </p>

          <div
            style={{ display: 'flex', flexDirection: 'column', gap: '8px', marginBottom: '24px' }}
          >
            <label
              htmlFor="mass-concepts"
              className="form-label"
              style={{ margin: 0, textTransform: 'uppercase', letterSpacing: '0.5px' }}
            >
              Lista de conceptos
            </label>
            <textarea
              id="mass-concepts"
              disabled={massGenerating || !!pendingImport.current}
              className="form-input"
              style={{ minHeight: '200px', padding: '12px', resize: 'vertical' }}
              value={massInput}
              onChange={(e) => setMassInput(e.target.value)}
              placeholder="Ejemplo:&#10;Polimorfismo&#10;Herencia&#10;Encapsulación&#10;Abstracción"
            />
          </div>

          <button
            className="btn btn-primary"
            style={{ width: '100%', padding: '16px', fontSize: '1.1rem' }}
            onClick={handleMassAdd}
            disabled={massGenerating}
          >
            {massGenerating ? (
              <span className="spinner-sm" />
            ) : (
              <span className="flex items-center justify-center gap-2">
                <ListPlus className="w-5 h-5" />{' '}
                {pendingImport.current ? (
                  'Reintentar guardado'
                ) : (
                  <>
                    Generar y añadir <span className="kbd-hint">Ctrl+Intro</span>
                  </>
                )}
              </span>
            )}
          </button>
          {importProgress && (
            <p role="status" className="import-progress">
              Guardadas {importProgress.saved} de {importProgress.total} tarjetas.
            </p>
          )}
          {pendingImport.current && !massGenerating && (
            <div className="import-recovery">
              <p>
                Las tarjetas confirmadas están guardadas. Reintenta para continuar con las
                pendientes.
              </p>
              <button
                type="button"
                className="sheet-action"
                onClick={() => {
                  pendingImport.current = null;
                  setImportProgress(null);
                  setMassInput('');
                }}
              >
                Descartar pendientes
              </button>
            </div>
          )}
        </div>
      ) : (
        <div
          style={{
            display: 'grid',
            gridTemplateColumns: 'repeat(auto-fit, minmax(min(100%, 350px), 1fr))',
            gap: '1.5rem',
          }}
        >
          <div
            className="card"
            style={{ display: 'flex', flexDirection: 'column', gap: '1.25rem' }}
          >
            {targetFields}
            {/* Front */}
            <div className="add-card-side">
              <span className="add-card-label">Frente</span>
              <div className="add-card-editor">
                <div className="add-card-tools" role="toolbar" aria-label="Herramientas del frente">
                  <button
                    type="button"
                    className="add-card-tool"
                    onClick={handleDefinition}
                    title="Definición con IA"
                    disabled={lookingUpDef}
                  >
                    <BookA size={16} aria-hidden="true" />
                    <span>{lookingUpDef ? '...' : 'Def. IA'}</span>
                  </button>
                  <button
                    type="button"
                    className="add-card-tool"
                    onClick={handleAutoImage}
                    title="Foto automática del término"
                    aria-label="Elegir una foto del término para el frente"
                  >
                    <Image size={16} aria-hidden="true" />
                    <span>Auto</span>
                  </button>
                  <button
                    type="button"
                    className="add-card-tool"
                    onClick={() => handleGalleryPick('front')}
                    title="Subir una imagen"
                  >
                    <Folder size={16} aria-hidden="true" />
                    <span>Galería</span>
                  </button>
                  <button
                    type="button"
                    className="add-card-tool"
                    onClick={() => handleOpenImageSearch('front')}
                    title="Buscar una imagen"
                  >
                    <Search size={16} aria-hidden="true" />
                    <span>Buscar</span>
                  </button>
                </div>
                <div
                  className="add-card-editable"
                  contentEditable
                  role="textbox"
                  aria-multiline="true"
                  aria-label="Frente de la tarjeta"
                  tabIndex={0}
                  ref={frontContentRef}
                  onInput={handleFieldChange('front')}
                  onPaste={handlePaste('front')}
                />
              </div>
            </div>

            {/* Back */}
            <div className="add-card-side">
              <span className="add-card-label">Dorso</span>
              <div className="add-card-editor">
                <div className="add-card-tools" role="toolbar" aria-label="Herramientas del dorso">
                  <button
                    type="button"
                    className="add-card-tool"
                    onClick={() => handleGalleryPick('back')}
                    title="Subir una imagen"
                  >
                    <Folder size={16} aria-hidden="true" />
                    <span>Galería</span>
                  </button>
                  <button
                    type="button"
                    className="add-card-tool"
                    onClick={() => handleOpenImageSearch('back')}
                    title="Buscar una imagen"
                  >
                    <Search size={16} aria-hidden="true" />
                    <span>Buscar</span>
                  </button>
                </div>
                <div
                  className="add-card-editable"
                  contentEditable
                  role="textbox"
                  aria-multiline="true"
                  aria-label="Dorso de la tarjeta"
                  tabIndex={0}
                  ref={backContentRef}
                  onInput={handleFieldChange('back')}
                  onPaste={handlePaste('back')}
                />
              </div>
            </div>
          </div>

          {/* La misma tarjeta que saldrá al estudiar; se le da la vuelta al tocarla. */}
          <div className="add-card-aside">
            <div className="add-card-preview">
              <div className="add-card-preview-head">
                <span className="add-card-label">Vista previa</span>
                {selectedType === 'reverse' && (
                  <SegmentedControl
                    options={[
                      { label: 'Normal', value: 'normal' },
                      { label: 'Al revés', value: 'reverse' },
                    ]}
                    value={previewReversed ? 'reverse' : 'normal'}
                    onChange={(value) => {
                      setPreviewReversed(value === 'reverse');
                      setPreviewFlipped(false);
                    }}
                    className="add-card-preview-switch"
                  />
                )}
              </div>
              <div
                className="add-card-preview-card"
                role="presentation"
                onClick={() => previewFlipped && setPreviewFlipped(false)}
                onKeyDown={(e) => {
                  if (previewFlipped && (e.key === ' ' || e.key === 'Enter')) {
                    e.preventDefault();
                    setPreviewFlipped(false);
                  }
                }}
              >
                <FlashCard
                  front={previewFront}
                  back={previewBack}
                  isFlipped={previewFlipped}
                  onFlip={() => setPreviewFlipped(true)}
                  cardState="new"
                />
              </div>
              <p className="add-card-preview-hint">
                {previewFlipped ? 'Respuesta' : 'Pregunta'} · tócala para darle la vuelta
              </p>
            </div>
            <div className="card add-card-finish">
              {/* Tags */}
              <div className="add-card-side">
                <label htmlFor="add-card-tags" className="add-card-label">
                  Etiquetas
                </label>
                <div
                  className="add-card-editor add-card-tags"
                  role="presentation"
                  onClick={() => tagInputRef.current?.focus()}
                >
                  {tags.map((tag) => (
                    <span key={tag} className="add-card-chip">
                      {tag}
                      <button
                        type="button"
                        aria-label={`Quitar etiqueta ${tag}`}
                        onClick={(e) => {
                          e.stopPropagation();
                          removeTag(tag);
                        }}
                      >
                        <X size={12} aria-hidden="true" />
                      </button>
                    </span>
                  ))}
                  <input
                    id="add-card-tags"
                    ref={tagInputRef}
                    aria-label="Añadir etiquetas"
                    placeholder={tags.length === 0 ? 'Escribe una y pulsa Intro' : ''}
                    value={tagInput}
                    onChange={(e) => setTagInput(e.target.value)}
                    onKeyDown={handleTagKeyDown}
                  />
                </div>
              </div>

              <div className="add-card-actions">
                <button
                  className="btn btn-primary"
                  style={{ flex: 1 }}
                  onClick={() => handleAdd(false)}
                  disabled={saving}
                >
                  {saving ? (
                    'Guardando...'
                  ) : (
                    <>
                      Añadir <span className="kbd-hint">Ctrl+Intro</span>
                    </>
                  )}
                </button>
                <button
                  className="btn btn-secondary"
                  style={{ flex: 1 }}
                  onClick={() => handleAdd(true)}
                  disabled={saving}
                >
                  Añadir y cerrar
                </button>
              </div>
            </div>
          </div>
        </div>
      )}

      {imageSearchModalInfo && (
        <ImageSearchModal
          isOpen={true}
          initialQuery={imageSearchModalInfo.query}
          title={
            imageSearchModalInfo.field === 'auto'
              ? `Elige una foto de «${imageSearchModalInfo.query}»`
              : undefined
          }
          onSelect={(url: string) => handleImageSearchSelect(url, imageSearchModalInfo.field)}
          onClose={() => setImageSearchModalInfo(null)}
        />
      )}
    </div>
  );
}
